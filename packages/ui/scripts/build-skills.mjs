// Assembles the layered skills folder (repo-root `skills/designsystem/`) from the existing
// sources, so there is still one source of truth:
//   schemas/registry.json            -> components.md (index)
//   docs/system/shared-rules.md      -> rules.md (+ foundations/*.md for the other system docs)
//   docs/system/page-patterns.md     -> patterns/page-layout.md, patterns/edit-drawer-pattern.md
//   schemas/<name>.manifest.json     -> <name>/references/props.json
//   schemas/<name>.md                -> <name>/references/pattern.md (consumer sections only; contributor sections are dropped)
// Run `node scripts/build-skills.mjs` from packages/ui. Output is generated; do not hand-edit.

import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const out = resolve(pkg, '../../skills/designsystem')
const read = p => readFileSync(join(pkg, p), 'utf8')
const write = (p, s) => {
  mkdirSync(dirname(join(out, p)), { recursive: true })
  // Put the generated-file notice after any frontmatter so the frontmatter still parses.
  const m = s.match(/^---\n[\s\S]*?\n---\n\n?/)
  const body = m ? m[0] + header + s.slice(m[0].length) : header + s
  writeFileSync(join(out, p), body.endsWith('\n') ? body : body + '\n')
}
const stripFrontmatter = s => s.replace(/^---\n[\s\S]*?\n---\n/, '')

rmSync(out, { recursive: true, force: true })
const header =
  '<!-- Generated by packages/ui/scripts/build-skills.mjs. Do not edit; change the source and rebuild. -->\n\n'

// Sections of a component pattern doc that are for people working in canary; not shipped.
const MAINTAINER = /^## (How to Contribute|References|Questions\?)/
const trimRule = t => t.replace(/\n---\s*$/, '\n').trimEnd() + '\n'
function consumerPattern(doc) {
  const [head, ...secs] = doc.split(/^(?=## )/m)
  const consumerHead = head.replace(
    /> \*\*This file is hand-written judgment only\.\*\*[\s\S]*?Don't copy them here\.\n/,
    '> Props, values, defaults and tokens are in [props.json](props.json). This file is judgment only:\n> when to use it, how to compose it, and known gaps.\n'
  )
  // Drop Figma / Code Connect material from the consumer copy: checklist items, table rows, and the tag note.
  const noFigma = t =>
    t
      .replace(/^- \[ \] .*(?:\n {6}.*)*\n?/gm, i => (/figma|code connect/i.test(i) ? '' : i))
      .replace(/^\|.*(?:Figma|Code Connect).*\n/gm, '')
      .replace(/^`forest-green` and `lime` exist in code but not in the Figma[\s\S]*?yet\.\n\n?/m, '')
      .replace('(DRW-001 to DRW-004)', '(DRW-002 to DRW-004)')
  const fix = t =>
    noFigma(t)
      .replace(/by `ds-check`/g, 'by tooling')
      .replace(
        '[`docs/system/page-patterns.md`](../docs/system/page-patterns.md)',
        '[the edit-drawer pattern](../../patterns/edit-drawer-pattern.md)'
      )
      .replace('`docs/system/visual-primitives.md`', '`foundations/visual-primitives.md`')
  const keep = secs.filter(x => !MAINTAINER.test(x))
  return fix(trimRule(consumerHead + keep.join('')))
}
// props.json is the manifest minus the Figma side (figma, bindings, props.designOnly, figmaNote),
// with rulesDocs paths rewritten to resolve inside this package.
function toProps(json, base) {
  const m = JSON.parse(rewriteRulesDocs(json, base))
  delete m.figma
  delete m.bindings
  if (m.props) delete m.props.designOnly
  const FIG = /figma|code connect/i
  if (m.knownGaps) m.knownGaps = m.knownGaps.filter(g => !FIG.test(g))
  const strip = o => {
    if (Array.isArray(o)) o.forEach(strip)
    else if (o && typeof o === 'object') {
      delete o.figmaNote
      if (o.trigger === 'no-figma-component') delete o.trigger
      if (typeof o.notes === 'string' && FIG.test(o.notes))
        o.notes = o.notes
          .split(/(?<=\.)\s+/)
          .filter(x => !FIG.test(x))
          .join(' ')
      Object.values(o).forEach(strip)
    }
  }
  strip(m)
  return JSON.stringify(m, null, 2) + '\n'
}
function rewriteRulesDocs(json, base) {
  const map = p =>
    p === 'docs/system/shared-rules.md'
      ? '../../rules.md'
      : p.startsWith('docs/system/')
        ? `../../foundations/${p.slice(12)}`
        : p === `schemas/${base}.md`
          ? 'pattern.md'
          : p
  return json.replace(
    /("rulesDocs"\s*:\s*\[)([\s\S]*?)(\])/,
    (_, a, list, c) => a + list.replace(/"([^"]+\.md)"/g, (_m, p) => `"${map(p)}"`) + c
  )
}

// components + per-component folders
const registry = JSON.parse(read('schemas/registry.json'))
const rows = []
for (const s of registry.skills) {
  const name = s.id.replace(/^canary\./, '')
  const base = s.manifest.replace(/^schemas\//, '').replace(/\.manifest\.json$/, '')
  mkdirSync(join(out, name, 'references'), { recursive: true })
  mkdirSync(join(out, name, 'references'), { recursive: true })
  writeFileSync(join(out, name, 'references/props.json'), toProps(read(s.manifest), base))
  write(`${name}/references/pattern.md`, consumerPattern(read(`schemas/${base}.md`)))
  write(
    `${name}/SKILL.md`,
    `---\nname: ${name}\ndescription: ${s.description}\n---\n\n# ${s.name}\n\nImport: \`import { ${s.export} } from '${s.import}'\`\n\nRead in this order:\n\n1. [references/props.json](references/props.json): the contract. Props, values, rules. If a prop or value is not here, it does not exist.\n2. [references/pattern.md](references/pattern.md): when to use it, composition, judgment calls.\n\nThen check [../rules.md](../rules.md) before writing code.\n`
  )
  rows.push(`| [${s.name}](${name}/SKILL.md) | \`${s.export}\` | ${s.description} |`)
}
write(
  'components.md',
  `# Components\n\nIndex of components that have a contract. Open only the one you need. A component not listed has no contract: say so, then read its source.\n\n| Component | Export | Use for |\n| --- | --- | --- |\n${rows.join('\n')}\n\nPage and composition patterns: see [rules.md](rules.md).\n`
)

// rules + foundations
const foundations = readdirSync(join(pkg, 'docs/system')).filter(
  f => f !== 'shared-rules.md' && f !== 'page-patterns.md'
)
for (const f of foundations) write(`foundations/${f}`, read(`docs/system/${f}`))
write(
  'rules.md',
  `${read('docs/system/shared-rules.md').replace('(`page-patterns.md` and any `*-patterns.md` that follows it)', '(the files in `patterns/`)')}\n## Patterns\n\n- [page-layout](patterns/page-layout.md): settings list page\n- [edit-drawer-pattern](patterns/edit-drawer-pattern.md): create/edit drawer\n\n## Foundations\n\n${foundations.map(f => `- [${f.replace(/\.md$/, '')}](foundations/${f})`).join('\n')}\n`
)

// patterns: split page-patterns.md on its "## " sections
const sections = stripFrontmatter(read('docs/system/page-patterns.md')).split(/^(?=## )/m)
const pick = title => {
  const s = sections.find(x => x.startsWith(`## ${title}`))
  if (!s) throw new Error(`page-patterns.md: missing section "${title}"`)
  return s
    .replace(/^## /, '# ')
    .replace(
      '`schemas/drawer.manifest.json` and\n`schemas/drawer.md`',
      '`drawer/references/props.json` and\n`drawer/references/pattern.md`'
    )
}
const intro = sections[0]
  .replace(
    'the manifest (`schemas/{component}.manifest.json`) where one exists, otherwise in\n`dist/components.d.ts`',
    "the component's `references/props.json` where one exists, otherwise in the installed\npackage's `dist/components.d.ts`"
  )
  .trim()
const tail = 'Both patterns inherit everything in [rules.md](../rules.md).\n'
write('patterns/page-layout.md', `${intro}\n\n${pick('Settings list page')}\n${tail}`)
write('patterns/edit-drawer-pattern.md', `${intro}\n\n${pick('Create / edit drawer')}\n${tail}`)

console.log(`skills/designsystem built: ${registry.skills.length} components`)
