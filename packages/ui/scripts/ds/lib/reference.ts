import { dirname, relative } from 'node:path'

import { parseGuide, type GuideHeading } from './guide.ts'

type PropValue = string | number | boolean | (string | number | boolean)[]

interface RefProp {
  name: string
  type: string
  values?: string[]
  required?: boolean
  default?: unknown
  notes?: string
  codeNote?: string
  constraint?: string
}

interface RefManifest {
  status: string
  code: { export: string; import: string; path: string }
  purpose: { summary: string; useWhen: string[]; doNotUseWhen: string[] }
  props: { shared: RefProp[]; designOnly: RefProp[]; codeOnly: RefProp[] }
  constraints?: {
    when: Record<string, PropValue>
    forbid?: string[]
    require?: string[]
    rule: string
    enforcedBy?: string
  }[]
  illegalCombinations?: { combination: Record<string, PropValue>; side: string; reason: string; rule?: string }[]
  accessibility?: { keyboardSupport: boolean | string[]; notes?: string }
  tokens: { rootClass?: string; rule?: string; refs: Record<string, string> }
  examples?: { correct?: string[]; incorrect?: (string | { code: string; violates: string[] })[] }
  knownGaps?: (string | { summary: string; rule?: string; source?: string })[]
}

interface RefRule {
  id: string
  title: string
  status: string
  tier?: number
  check?: string | string[]
}

interface RefFrontMatter {
  rules: RefRule[]
  gaps?: RefRule[]
}

export interface ReferenceSource {
  manifest: unknown
  manifestPath: string
  guideSource: string
  guidePath: string
  /** Absolute path the reference will be written to; links are made relative to it. */
  outputPath: string
  /** Patterns that compose this component, with the path of each pattern's reference. */
  usedIn?: { name: string; referencePath: string }[]
}

interface PatternComponent {
  export: string
  manifest?: string | null
  path?: string
  role: string
}

interface RefPattern {
  status: string
  purpose: { summary: string; useWhen: string[]; doNotUseWhen: string[] }
  components: PatternComponent[]
  anatomy: {
    slot: string
    fill: string
    required: boolean | string
    props?: Record<string, unknown>
    rules?: string[]
    notes?: string
  }[]
  states?: { source: string; values: string[]; map?: Record<string, unknown> | null; notes?: string }
  constraints?: { when: string; use: string; instead?: string; rule: string; enforcedBy?: string; notes?: string }[]
  figma: { fileKey?: string | null; nodeId?: string | null; notes?: string }
  examples?: {
    correct?: { code: string; source?: string }[]
    incorrect?: { code: string; violates: string[]; source?: string }[]
  }
  knownGaps?: { summary: string; rule?: string; source?: string }[]
}

export interface PatternSource extends ReferenceSource {
  name: string
  /** Component export -> absolute path of its generated reference. */
  componentRefs: Map<string, string>
}

export interface IndexEntry {
  component: string
  summary: string
  referencePath: string
}

const HEADER = (sources: string[]): string =>
  `<!-- Generated by \`pnpm ds:generate\` from ${sources.join(' and ')}. Do not edit. Edit the sources and regenerate. -->`

const cell = (text: string): string => text.replace(/\|/g, '\\|').replace(/\n+/g, ' ')

const code = (text: string): string => `\`${text}\``

const formatValue = (value: PropValue): string =>
  Array.isArray(value) ? value.map(v => code(String(v))).join(' or ') : code(String(value))

const formatWhen = (when: Record<string, PropValue>): string =>
  Object.entries(when)
    .map(([prop, value]) => `${code(prop)} is ${formatValue(value)}`)
    .join(' and ')

const checks = (check: RefRule['check']): string[] =>
  check === undefined ? [] : Array.isArray(check) ? check : [check]

const firstSentence = (text: string): string => {
  const match = /^.+?[.!?](?=\s|$)/.exec(text.trim())
  return match ? match[0] : text.trim()
}

/** Prose under a rule heading, up to the next heading of the same or higher level. */
const sectionBody = (lines: string[], heading: GuideHeading): string => {
  const body: string[] = []
  let inFence = false
  for (let index = heading.line; index < lines.length; index++) {
    const text = lines[index]
    if (text.startsWith('```')) inFence = !inFence
    const level = /^(#{1,6}) /.exec(text)?.[1].length
    if (!inFence && level !== undefined && level <= heading.level) break
    body.push(text)
  }
  return body.join('\n').trim()
}

/**
 * The guide's intro: text between the H1 and the first level-2 heading, with
 * HTML comments removed. Comments hold notes for guide authors.
 */
const intro = (lines: string[]): string => {
  const body: string[] = []
  for (let index = lines.indexOf('---', 1) + 1; index < lines.length; index++) {
    const text = lines[index]
    if (text.startsWith('## ')) break
    if (!text.startsWith('# ')) body.push(text)
  }
  return body
    .join('\n')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}

/** Level-2 guide sections that are not rules or known gaps, such as Do's and Do Not's. */
const proseSections = (lines: string[]): { title: string; body: string }[] => {
  const start = lines.indexOf('---', 1) + 1
  const sections: { title: string; body: string }[] = []
  let inFence = false
  for (let index = start; index < lines.length; index++) {
    const text = lines[index]
    if (text.startsWith('```')) inFence = !inFence
    const title = /^## (.+)$/.exec(text)?.[1]
    if (inFence || !title || /^[A-Z]{2,5}-\d{3} /.test(title) || title.trim() === 'Known gaps') continue
    const heading: GuideHeading = { level: 2, id: '', title, line: index + 1, inKnownGaps: false }
    sections.push({ title: title.replace(/^Architecture: /, ''), body: sectionBody(lines, heading) })
  }
  return sections
}

const propRows = (props: RefProp[]): string[] =>
  props.map(prop => {
    const type = prop.type === 'enum' && prop.values ? prop.values.map(code).join(' \\| ') : code(prop.type)
    const required = prop.required ? 'yes' : 'no'
    const fallback = prop.default === undefined ? '' : code(JSON.stringify(prop.default))
    const notes = [prop.constraint, prop.codeNote ?? prop.notes].filter(Boolean).join(' ')
    return `| ${code(prop.name)} | ${type} | ${required} | ${fallback} | ${cell(notes)} |`
  })

const linkTo = (from: string, to: string): string => relative(dirname(from), to)

type Push = (...chunk: string[]) => void

const renderRules = (
  push: Push,
  frontMatter: RefFrontMatter,
  lines: string[],
  headingFor: Map<string, GuideHeading>
): void => {
  push(
    '## Rules',
    '',
    'Status `ratified` is decided by Design, `proposed` is a draft, `open` is a question, `retired` no longer applies. Check `review` means nothing automatic enforces the rule.',
    '',
    '| ID | Rule | Tier | Status |',
    '| -- | ---- | ---- | ------ |',
    ...frontMatter.rules.map(rule => `| ${rule.id} | ${cell(rule.title)} | ${rule.tier ?? ''} | ${rule.status} |`),
    ''
  )
  for (const rule of frontMatter.rules) {
    const heading = headingFor.get(rule.id)
    push(`### ${rule.id} — ${rule.title}`, '')
    push(`Checked by: ${checks(rule.check).map(code).join(', ') || code('review')}.`, '')
    if (heading) push(sectionBody(lines, heading), '')
  }
}

const renderGaps = (
  push: Push,
  gaps: { summary: string; rule?: string; source?: string }[],
  frontMatter: RefFrontMatter,
  lines: string[],
  headingFor: Map<string, GuideHeading>,
  intro: string
): void => {
  const guideGaps = frontMatter.gaps ?? []
  if (gaps.length === 0 && guideGaps.length === 0) return
  push('## Known gaps', '', intro, '')
  for (const entry of gaps) {
    const meta = [entry.rule, entry.source ? `source: ${entry.source}` : ''].filter(Boolean).join('; ')
    push(`- ${entry.summary}${meta ? ` (${meta})` : ''}`)
  }
  push('')
  for (const gap of guideGaps) {
    const heading = headingFor.get(gap.id)
    push(`### ${gap.id} — ${gap.title}`, '')
    if (heading) push(sectionBody(lines, heading), '')
  }
}

const finish = (out: string[]): string =>
  `${out
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trimEnd()}\n`

export const renderReference = (source: ReferenceSource): string => {
  const manifest = source.manifest as RefManifest
  const guide = parseGuide(source.guideSource)
  const frontMatter = guide.frontMatter as RefFrontMatter
  const lines = source.guideSource.split('\n')
  const headingFor = new Map(guide.headings.map(heading => [heading.id, heading]))
  const manifestLink = linkTo(source.outputPath, source.manifestPath)
  const guideLink = linkTo(source.outputPath, source.guidePath)
  const out: string[] = []
  const push = (...chunk: string[]): void => {
    out.push(...chunk)
  }

  push(
    HEADER([manifestLink.split('/').pop() ?? '', guideLink.split('/').pop() ?? '']),
    '',
    `# ${manifest.code.export}`,
    '',
    '```tsx',
    manifest.code.import,
    '```',
    '',
    `Status: ${code(manifest.status)}. Sources: [manifest](${manifestLink}), [guide](${guideLink}).`,
    '',
    manifest.purpose.summary,
    '',
    ...(intro(lines) ? ['## About this guide', '', intro(lines), ''] : []),
    '## Use when',
    '',
    ...manifest.purpose.useWhen.map(item => `- ${item}`),
    '',
    '## Do not use when',
    '',
    ...manifest.purpose.doNotUseWhen.map(item => `- ${item}`),
    ''
  )

  if (source.usedIn?.length)
    push(
      '## Used in patterns',
      '',
      ...source.usedIn.map(
        pattern =>
          `- [${pattern.name}](${linkTo(source.outputPath, pattern.referencePath)}): read it before composing ${manifest.code.export} with other components.`
      ),
      ''
    )

  push(
    '## Props',
    '',
    '| Prop | Type | Required | Default | Notes |',
    '| ---- | ---- | -------- | ------- | ----- |',
    ...propRows([...manifest.props.shared, ...manifest.props.codeOnly]),
    ''
  )

  if (manifest.props.designOnly.length > 0)
    push(
      `Figma-only properties, with no code prop: ${manifest.props.designOnly.map(prop => code(prop.name)).join(', ')}.`,
      ''
    )

  const constraints = manifest.constraints ?? []
  if (constraints.length > 0) {
    push('## Constraints', '')
    for (const c of constraints) {
      const parts = [
        c.forbid?.length ? `do not pass ${c.forbid.map(code).join(', ')}` : '',
        c.require?.length ? `pass ${c.require.map(code).join(', ')}` : ''
      ].filter(Boolean)
      push(`- When ${formatWhen(c.when)}: ${parts.join('; ')}. (${c.rule}, enforced by ${c.enforcedBy ?? 'none'})`)
    }
    push('')
  }

  const illegal = manifest.illegalCombinations ?? []
  if (illegal.length > 0) {
    push('## Illegal combinations', '')
    for (const c of illegal)
      push(`- ${formatWhen(c.combination)} (${c.side}): ${c.reason}${c.rule ? ` (${c.rule})` : ''}`)
    push('')
  }

  for (const section of proseSections(lines)) push(`## ${section.title}`, '', section.body, '')

  if (manifest.accessibility) {
    const keys = manifest.accessibility.keyboardSupport
    push(
      '## Accessibility',
      '',
      `Keyboard support: ${Array.isArray(keys) ? keys.map(code).join(', ') || 'none' : keys ? 'yes' : 'none'}.`,
      ''
    )
    if (manifest.accessibility.notes) push(manifest.accessibility.notes, '')
  }

  push('## Tokens', '')
  if (manifest.tokens.rootClass) push(`Root class: ${code(manifest.tokens.rootClass)}.`)
  if (manifest.tokens.rule) push(`Token rule: ${code(manifest.tokens.rule)}.`)
  push('', ...Object.entries(manifest.tokens.refs).map(([role, token]) => `- ${role}: ${code(token)}`), '')

  renderRules(push, frontMatter, lines, headingFor)

  const examples = manifest.examples ?? {}
  if ((examples.correct ?? []).length > 0) push('## Correct', '', '```tsx', ...(examples.correct ?? []), '```', '')
  if ((examples.incorrect ?? []).length > 0) {
    push('## Incorrect', '')
    for (const example of examples.incorrect ?? []) {
      const entry = typeof example === 'string' ? { code: example, violates: [] } : example
      push('```tsx', entry.code, '```', '')
      if (entry.violates.length > 0) push(`Violates ${entry.violates.join(', ')}.`, '')
    }
  }

  renderGaps(
    push,
    (manifest.knownGaps ?? []).map(gap => (typeof gap === 'string' ? { summary: gap } : gap)),
    frontMatter,
    lines,
    headingFor,
    'Figma, code and docs disagree here. Check the cited source before copying this behavior.'
  )

  return finish(out)
}

const formatProps = (props: Record<string, unknown>): string =>
  Object.entries(props)
    .map(
      ([name, value]) =>
        `${code(name)}: ${(Array.isArray(value) ? value : [value]).map(v => code(String(v))).join(', ')}`
    )
    .join('; ')

export const renderPattern = (source: PatternSource): string => {
  const manifest = source.manifest as RefPattern
  const guide = parseGuide(source.guideSource)
  const frontMatter = guide.frontMatter as RefFrontMatter
  const lines = source.guideSource.split('\n')
  const headingFor = new Map(guide.headings.map(heading => [heading.id, heading]))
  const manifestLink = linkTo(source.outputPath, source.manifestPath)
  const guideLink = linkTo(source.outputPath, source.guidePath)
  const out: string[] = []
  const push: Push = (...chunk) => {
    out.push(...chunk)
  }

  push(
    HEADER([manifestLink.split('/').pop() ?? '', guideLink.split('/').pop() ?? '']),
    '',
    `# ${source.name} pattern`,
    '',
    `Status: ${code(manifest.status)}. Sources: [manifest](${manifestLink}), [guide](${guideLink}).`,
    '',
    manifest.purpose.summary,
    '',
    ...(intro(lines) ? ['## About this guide', '', intro(lines), ''] : []),
    '## Use when',
    '',
    ...manifest.purpose.useWhen.map(item => `- ${item}`),
    '',
    '## Do not use when',
    '',
    ...manifest.purpose.doNotUseWhen.map(item => `- ${item}`),
    '',
    '## Components',
    '',
    '| Component | Role | Reference |',
    '| --------- | ---- | --------- |',
    ...manifest.components.map(component => {
      const ref = source.componentRefs.get(component.export)
      const link = ref
        ? `[${linkTo(source.outputPath, ref)}](${linkTo(source.outputPath, ref)})`
        : `No contract. Source: ${code(component.path ?? '')}`
      return `| ${component.export} | ${cell(component.role)} | ${link} |`
    }),
    '',
    '## Anatomy',
    '',
    'Slots in render order, outermost first.',
    '',
    '| Slot | Fill | Required | Props | Rules | Notes |',
    '| ---- | ---- | -------- | ----- | ----- | ----- |',
    ...manifest.anatomy.map(
      slot =>
        `| ${code(slot.slot)} | ${code(slot.fill)} | ${cell(String(slot.required))} | ${cell(slot.props ? formatProps(slot.props) : '')} | ${(slot.rules ?? []).join(', ')} | ${cell(slot.notes ?? '')} |`
    ),
    ''
  )

  if (manifest.states) {
    const { states } = manifest
    push('## States', '', `Source: ${code(states.source)}.`, '', `Values: ${states.values.map(code).join(', ')}.`, '')
    if (states.map)
      push(
        ...Object.entries(states.map).map(([state, props]) => `- ${code(state)}: ${code(JSON.stringify(props))}`),
        ''
      )
    else push('No mapping from state to props yet.', '')
    if (states.notes) push(states.notes, '')
  }

  const constraints = manifest.constraints ?? []
  if (constraints.length > 0) {
    push('## Constraints', '')
    for (const c of constraints)
      push(
        `- When ${c.when.charAt(0).toLowerCase()}${c.when.slice(1)}: use ${c.use}${c.instead ? `, not ${c.instead}` : ''}. (${c.rule}, enforced by ${c.enforcedBy ?? 'none'})${c.notes ? ` ${c.notes}` : ''}`
      )
    push('')
  }

  for (const section of proseSections(lines)) push(`## ${section.title}`, '', section.body, '')

  const { figma } = manifest
  push(
    '## Figma',
    '',
    figma.fileKey
      ? `File ${code(figma.fileKey)}${figma.nodeId ? `, node ${code(figma.nodeId)}` : ''}.`
      : 'No Figma counterpart linked.',
    ''
  )
  if (figma.notes) push(figma.notes, '')

  renderRules(push, frontMatter, lines, headingFor)

  const examples = manifest.examples ?? {}
  if ((examples.correct ?? []).length > 0) {
    push('## Correct', '')
    for (const example of examples.correct ?? []) {
      push('```tsx', example.code, '```', '')
      if (example.source) push(`Source: ${example.source}.`, '')
    }
  }
  if ((examples.incorrect ?? []).length > 0) {
    push('## Incorrect', '')
    for (const example of examples.incorrect ?? []) {
      push('```tsx', example.code, '```', '', `Violates ${example.violates.join(', ')}.`, '')
      if (example.source) push(`Source: ${example.source}.`, '')
    }
  }

  renderGaps(
    push,
    manifest.knownGaps ?? [],
    frontMatter,
    lines,
    headingFor,
    'Open questions. Nothing here is decided. Check the cited source before copying this behavior.'
  )

  return finish(out)
}

const indexRows = (entries: IndexEntry[], indexPath: string): string[] =>
  [...entries]
    .sort((a, b) => a.component.localeCompare(b.component))
    .map(
      entry =>
        `| ${entry.component} | ${cell(firstSentence(entry.summary))} | [${linkTo(indexPath, entry.referencePath)}](${linkTo(indexPath, entry.referencePath)}) |`
    )

export const renderIndex = (entries: IndexEntry[], indexPath: string, patterns: IndexEntry[] = []): string => {
  const rows = indexRows(entries, indexPath)
  const patternRows =
    patterns.length === 0
      ? []
      : [
          '## Patterns',
          '',
          'Patterns compose several components into one screen element. Read the pattern before composing its components yourself.',
          '',
          '| Pattern | Use for | Reference |',
          '| ------- | ------- | --------- |',
          ...indexRows(patterns, indexPath),
          ''
        ]
  return [
    HEADER(['every *.manifest.json and *.guide.md under packages/ui/src/components and packages/ui/src/patterns']),
    '',
    '# Component index',
    '',
    'Components in `@harnessio/ui` that have a contract. Read a component’s reference before using it. Use only the props, values and tokens its reference lists.',
    '',
    '| Component | Use for | Reference |',
    '| --------- | ------- | --------- |',
    ...rows,
    '',
    ...patternRows
  ].join('\n')
}
