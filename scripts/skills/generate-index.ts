/**
 * Builds the indexes in skills/harness-design-system/ from the frontmatter of each guide in
 * skills/harness-design-system/<name>/SKILL.md. Only skills/harness-design-system/ is a skill for npx skills;
 * the nested folders install with it and are reached through these indexes.
 *
 *   pnpm skills:index           write components.md (and patterns.md once pattern skills exist)
 *   pnpm skills:index --check   exit 1 if the files on disk are out of date
 *
 * Frontmatter each guide needs:
 *
 *   ---
 *   name: button
 *   description: ...
 *   metadata:
 *     category: Actions           # heading the entry is listed under
 *     use-when: ...               # one line; falls back to description
 *     type: pattern               # optional; default is component
 *   ---
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const INDEX_DIR: string = resolve(__dirname, '../../skills/harness-design-system')
const UNCATEGORISED: string = 'Other'

type SkillType = 'component' | 'pattern'

interface SkillEntry {
  folder: string
  title: string
  category: string
  useWhen: string
  type: SkillType
}

const readValue = (raw: string, file: string, key: string): string => {
  const value = raw.trim()
  if (value.startsWith('"') && value.endsWith('"') && value.length > 1) return JSON.parse(value) as string
  if (value.startsWith("'") && value.endsWith("'") && value.length > 1) return value.slice(1, -1).replace(/''/g, "'")
  if (/: |\s#/.test(value)) {
    throw new Error(
      `${file}: "${key}" contains ": " or " #", which breaks YAML and makes npx skills skip it. Wrap it in quotes.`
    )
  }
  return value
}

const parseFrontmatter = (source: string, file: string): Record<string, string> => {
  const match = source.match(/^---\n([\s\S]*?)\n---\n/)
  if (!match) throw new Error(`${file}: no frontmatter`)

  const fields: Record<string, string> = {}
  let parent: string | null = null

  for (const line of match[1].split('\n')) {
    if (!line.trim()) continue
    const nested = line.match(/^ {2}([\w-]+):\s*(.*)$/)
    if (nested && parent) {
      fields[`${parent}.${nested[1]}`] = readValue(nested[2], file, `${parent}.${nested[1]}`)
      continue
    }
    const top = line.match(/^([\w-]+):\s*(.*)$/)
    if (!top) throw new Error(`${file}: cannot parse frontmatter line "${line}"`)
    parent = top[2] === '' ? top[1] : null
    if (top[2] !== '') fields[top[1]] = readValue(top[2], file, top[1])
  }

  return fields
}

const readTitle = (source: string, fallback: string): string => {
  const heading = source.match(/^# (.+)$/m)
  if (!heading) return fallback
  return heading[1].replace(/ (Component|Pattern)$/, '').trim()
}

const readSkill = (folder: string): SkillEntry | null => {
  const file = join(INDEX_DIR, folder, 'SKILL.md')
  if (!existsSync(file)) return null

  const source = readFileSync(file, 'utf8')
  const fields = parseFrontmatter(source, file)

  if (fields.name !== folder) throw new Error(`${file}: name "${fields.name}" must match folder "${folder}"`)
  if (!fields.description) throw new Error(`${file}: missing description`)

  const type = fields['metadata.type'] ?? 'component'
  if (type !== 'component' && type !== 'pattern') throw new Error(`${file}: unknown metadata.type "${type}"`)

  return {
    folder,
    title: readTitle(source, folder),
    category: fields['metadata.category'] ?? UNCATEGORISED,
    useWhen: fields['metadata.use-when'] ?? fields.description,
    type
  }
}

const renderIndex = (heading: string, intro: string, entries: SkillEntry[], footer: string): string => {
  const byCategory = new Map<string, SkillEntry[]>()
  for (const entry of entries) {
    byCategory.set(entry.category, [...(byCategory.get(entry.category) ?? []), entry])
  }

  const categories = [...byCategory.keys()].sort((a, b) => {
    if (a === UNCATEGORISED) return 1
    if (b === UNCATEGORISED) return -1
    return a.localeCompare(b)
  })

  const sections = categories.map(category => {
    const lines = byCategory
      .get(category)!
      .sort((a, b) => a.title.localeCompare(b.title))
      .map(entry => `- [${entry.title}](${entry.folder}/SKILL.md): ${entry.useWhen}`)
    return `## ${category}\n\n${lines.join('\n')}`
  })

  return (
    [
      `<!-- Generated by scripts/skills/generate-index.ts from each skill's frontmatter. Do not edit by hand. -->`,
      `# ${heading}`,
      intro,
      ...sections,
      footer
    ].join('\n\n') + '\n'
  )
}

const main = (): void => {
  const check = process.argv.includes('--check')

  const skills = readdirSync(INDEX_DIR, { withFileTypes: true })
    .filter(entry => entry.isDirectory())
    .map(entry => readSkill(entry.name))
    .filter((entry): entry is SkillEntry => entry !== null)

  const outputs: Array<{ path: string; content: string }> = [
    {
      path: join(INDEX_DIR, 'components.md'),
      content: renderIndex(
        'Components',
        'Components that have a guide, grouped by purpose. Open only the one you need. A component not listed here has no guide: say so rather than guessing its props.',
        skills.filter(skill => skill.type === 'component'),
        'Page and composition patterns: see [rules.md](rules.md).'
      )
    }
  ]

  const patterns = skills.filter(skill => skill.type === 'pattern')
  if (patterns.length > 0) {
    outputs.push({
      path: join(INDEX_DIR, 'patterns.md'),
      content: renderIndex(
        'Patterns',
        'Page and composition patterns that have a guide, grouped by purpose. Open only the one you need.',
        patterns,
        'Components: see [components.md](components.md).'
      )
    })
  }

  const stale = outputs.filter(({ path, content }) => !existsSync(path) || readFileSync(path, 'utf8') !== content)

  if (check) {
    if (stale.length === 0) return
    console.error(`Out of date: ${stale.map(({ path }) => path).join(', ')}. Run pnpm skills:index.`)
    process.exit(1)
  }

  for (const { path, content } of stale) {
    writeFileSync(path, content)
    console.log(`Wrote ${path}`)
  }
  if (stale.length === 0) console.log('Indexes already up to date.')
}

main()
